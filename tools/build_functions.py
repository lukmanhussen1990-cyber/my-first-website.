# --- tiny command emitter ----------------------------------------------------


def _rel(value: int, offset: int) -> str:
    total = value + offset
    return "~" if total == 0 else "~%d" % total


def pos(x: int, y: int, z: int) -> str:
    return "%s %s %s" % (_rel(x, OX), _rel(y, OY), _rel(z, OZ))


def states(**kwargs) -> str:
    if not kwargs:
        return ""
    parts = []
    for key, value in kwargs.items():
        key = key.replace("__", ":")
        if isinstance(value, bool):
            parts.append('"%s":%s' % (key, "true" if value else "false"))
        elif isinstance(value, int):
            parts.append('"%s":%d' % (key, value))
        else:
            parts.append('"%s":"%s"' % (key, value))
    return " [%s]" % ",".join(parts)


class Part(object):
    """One .mcfunction file."""

    def __init__(self, name, title):
        self.name = name
        self.title = title
        self.lines = ["# %s" % title, "# generated by tools/build_functions.py -- do not edit by hand", ""]

    # -- primitives --
    def cmd(self, line):
        self.lines.append(line)

    def note(self, text):
        self.lines.append("")
        self.lines.append("# %s" % text)

    def fill(self, x1, y1, z1, x2, y2, z2, block, st="", mode=""):
        tail = (" " + mode) if mode else ""
        self.cmd("fill %s %s %s%s%s" % (pos(x1, y1, z1), pos(x2, y2, z2), block, st, tail))

    def block(self, x, y, z, block, st=""):
        self.cmd("setblock %s %s%s" % (pos(x, y, z), block, st))

    # -- helpers --
    def cuboid(self, x1, y1, z1, x2, y2, z2, block, st=""):
        self.fill(x1, y1, z1, x2, y2, z2, block, st)

    def walls(self, x1, z1, x2, z2, y1, y2, block, st=""):
        """Four vertical walls (hollow box without floor or ceiling)."""
        self.fill(x1, y1, z1, x2, y2, z1, block, st)
        self.fill(x1, y1, z2, x2, y2, z2, block, st)
        self.fill(x1, y1, z1, x1, y2, z2, block, st)
        self.fill(x2, y1, z1, x2, y2, z2, block, st)

    def outline(self, x1, z1, x2, z2, y, block, st=""):
        self.walls(x1, z1, x2, z2, y, y, block, st)

    def row(self, coords, y, block, st=""):
        for x, z in coords:
            self.block(x, y, z, block, st)

    def door(self, x, y, z, wood="dark_oak", direction=1):
        """Place both halves of a door. direction 0=E 1=S 2=W 3=N."""
        base = "minecraft:%s_door" % wood
        self.block(x, y, z, base, states(direction=direction, door_hinge_bit=False,
                                         open_bit=False, upper_block_bit=False))
        self.block(x, y + 1, z, base, states(direction=direction, door_hinge_bit=False,
                                             open_bit=False, upper_block_bit=True))

    def bed(self, x, y, z, direction=0):
        """direction 0=S 1=W 2=N 3=E -- head is one block that way."""
        dx, dz = {0: (0, 1), 1: (-1, 0), 2: (0, -1), 3: (1, 0)}[direction]
        self.block(x, y, z, "minecraft:bed", states(direction=direction, head_piece_bit=False))
        self.block(x + dx, y, z + dz, "minecraft:bed", states(direction=direction, head_piece_bit=True))

    def stairs(self, x, y, z, block, facing, upside_down=False):
        """facing 0=E 1=W 2=S 3=N (Bedrock weirdo_direction)."""
        self.block(x, y, z, block, states(weirdo_direction=facing, upside_down_bit=upside_down))

    def stairs_run(self, x1, x2, z, y, block, facing, upside_down=False):
        self.fill(x1, y, z, x2, y, z, block,
                  states(weirdo_direction=facing, upside_down_bit=upside_down))

    def tree(self, x, z, y=Y_GROUND, height=5, log="minecraft:oak_log", leaf="minecraft:oak_leaves"):
        top = y + height
        self.fill(x, y + 1, z, x, top, z, log)
        self.fill(x - 2, top - 2, z - 2, x + 2, top - 1, z + 2, leaf, "", "keep")
        self.fill(x - 1, top, z - 1, x + 1, top, z + 1, leaf, "", "keep")
        self.block(x, top + 1, z, leaf)
        self.fill(x, y + 1, z, x, top, z, log)

    def lamp(self, x, z, y=Y_GROUND):
        self.fill(x, y + 1, z, x, y + 3, z, "minecraft:quartz_pillar")
        self.block(x, y + 4, z, "minecraft:sea_lantern")

    def write(self, directory):
        path = os.path.join(directory, "%s.mcfunction" % self.name)
        with open(path, "w") as handle:
            handle.write("\n".join(self.lines).rstrip() + "\n")
        return path, sum(1 for line in self.lines if line and not line.startswith("#"))


