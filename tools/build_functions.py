def main():
    if os.path.isdir(FUNC_DIR):
        shutil.rmtree(FUNC_DIR)
    os.makedirs(os.path.join(FUNC_DIR, "parts"))

    total = 0
    for item in PARTS:
        path, count = item.write(FUNC_DIR)
        total += count
        print("%-28s %4d commands" % (os.path.relpath(path, FUNC_DIR), count))
    print("-" * 42)
    print("%-28s %4d commands" % ("total", total))


if __name__ == "__main__":
    main()
