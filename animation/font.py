def glyph_w(ch):
    return len(F.get(ch.upper(), F[' '])[0])


def text_width(s, scale=1):
    """Width in pixels of a string rendered at the given integer scale."""
    if not s:
        return 0
    return (sum(glyph_w(c) + 1 for c in s) - 1) * scale


def text_cells(s, x, y, scale=1):
    """Yield (px, py, w, h) blocks for every lit pixel of the string."""
    cx = x
    for ch in s.upper():
        g = F.get(ch, F[' '])
        for ry, row in enumerate(g):
            for rx, c in enumerate(row):
                if c == '#':
                    yield (cx + rx * scale, y + ry * scale, scale, scale)
        cx += (len(g[0]) + 1) * scale
