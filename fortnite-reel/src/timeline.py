NFRAMES = int(round(TOTAL*FPS))
def seg_at(t):
    for s in SEGS:
        if s[1] <= t < s[2]: return s
    return SEGS[-1]
if __name__ == "__main__":
    frames=[]
    for f in range(NFRAMES):
        t=f/FPS; s=seg_at(t)
        frames.append([s[0], round(t-s[1],5), round(s[2]-s[1],5), round(t,5)])
    json.dump({"fps":FPS,"total":TOTAL,"segs":SEGS,"frames":frames}, open(os.path.join(os.path.dirname(__file__),"timeline.json"),"w"))
    print(NFRAMES, "frames")
