"""Pad the natural pauses of the provided voiceover a little (the voice itself is untouched)
so the reel breathes to ~60 s, and remap Whisper word timings onto the padded track.
Outputs: out/vo_padded.wav and src/words.js (caption timeline)."""
import json, subprocess, numpy as np, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SR = 44100
LEAD = 0.30
# (silence_start, silence_end, extra_pad) measured with ffmpeg silencedetect (-35 dB)
GAPS = [(3.281,3.719,.25),(5.862,6.286,.35),(9.646,10.126,.20),(14.507,14.949,.20),(19.329,19.801,.25),
        (21.957,22.410,.20),(25.514,25.980,.20),(28.253,28.709,.20),(31.869,32.299,.15),(32.862,33.410,.25),
        (37.696,38.137,.20),(40.106,40.548,.20),(44.032,44.512,.20),(46.862,47.277,.15),(51.453,51.888,.30)]
SHORT = [(0.981,1.248),(15.818,16.080),(52.800,53.050)]
os.makedirs(f"{ROOT}/out", exist_ok=True)
raw = subprocess.run(['ffmpeg','-v','error','-i',f'{ROOT}/assets/voiceover.mp3','-ac','1','-ar',str(SR),'-f','f32le','-'],capture_output=True).stdout
vo = np.frombuffer(raw, dtype=np.float32)
pieces=[np.zeros(int(LEAD*SR),np.float32)]; prev=0
for s,e,p in GAPS:
    mid=int((s+e)/2*SR); pieces += [vo[prev:mid], np.zeros(int(p*SR),np.float32)]; prev=mid
pieces.append(vo[prev:]); out=np.concatenate(pieces)
out.astype('<f4').tofile(f'{ROOT}/out/vo_padded.f32')
def remap(t):
    return t + LEAD + sum(p for s,e,p in GAPS if (s+e)/2 < t)
words=json.load(open(f'{ROOT}/assets/words_raw.json'))
sil=[(s,e) for s,e,_ in GAPS]+SHORT
for w in words:  # snap word edges out of detected silences
    for s,e in sil:
        if s-0.02 < w['s'] < e or (w['s'] <= s and w['e'] > e + 0.05): w['s']=e
        if s < w['e'] < e+0.02: w['e']=s
    if w['e']<=w['s']: w['e']=w['s']+0.15
# known whisper slips at phrase ends
for w in words:
    if w['w'].startswith('Congratulations'): w['e']=52.80
res=[]
for w in words:
    txt=re.sub(r"[^A-Za-z']","",w['w'])
    res.append({'w':txt[0].upper()+txt[1:],'s':round(remap(w['s']),3),'e':round(remap(w['e']),3)})
open(f'{ROOT}/src/words.js','w').write('// generated by audio/timeline.py\nexport const WORDS = '+json.dumps(res)+';\nexport const VO_END = %.3f;\n'%(len(out)/SR))
print('padded length %.2f s'%(len(out)/SR)); print(' '.join(f"{w['w']}@{w['s']:.2f}" for w in res))
