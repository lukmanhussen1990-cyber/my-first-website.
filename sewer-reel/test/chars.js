import * as THREE from 'three';
import { RoomEnvironment } from 'three/addons/environments/RoomEnvironment.js';
import { makePerson, makeBean, makePoop, makeFish, makeTree, makeToilet, makeBucket } from '../src/toys.js';
const W=1080,H=1920;
const renderer=new THREE.WebGLRenderer({antialias:true,preserveDrawingBuffer:true}); renderer.setSize(W,H,false);
renderer.shadowMap.enabled=true; renderer.toneMapping=THREE.ACESFilmicToneMapping; renderer.toneMappingExposure=1.0;
document.body.appendChild(renderer.domElement);
const scene=new THREE.Scene(); scene.background=new THREE.Color('#8cc8ff');
const pm=new THREE.PMREMGenerator(renderer); scene.environment=pm.fromScene(new RoomEnvironment(),0.04).texture; scene.environmentIntensity=0.35;
scene.add(new THREE.HemisphereLight('#dff0ff','#7a6a4a',1.3));
const sun=new THREE.DirectionalLight('#fff3df',2.6); sun.position.set(6,12,9); sun.castShadow=true; sun.shadow.mapSize.set(2048,2048); Object.assign(sun.shadow.camera,{left:-8,right:8,top:8,bottom:-8}); sun.shadow.bias=-0.0005; sun.shadow.normalBias=0.02; scene.add(sun);
const g=new THREE.Mesh(new THREE.PlaneGeometry(50,50),new THREE.MeshStandardMaterial({color:'#5aa83a'})); g.rotation.x=-Math.PI/2; g.receiveShadow=true; scene.add(g);
const faces=['smile','shock','squint','shout','joy','disgust'];
const people=[];
faces.forEach((f,i)=>{const p=makePerson({shirt:['#4f8fd6','#d9534f','#5cb85c','#f0ad4e','#9b59b6','#e67e22'][i], hat:i==3?'nightcap':i==2?'cap':i==4?'kerchief':null, hairStyle:i==4?'bun':'cap'}); p.position.set((i%3-1)*2.2, 0, Math.floor(i/3)*-3); p.userData.face.set(f); scene.add(p); people.push(p);});
// pinch nose pose on disgust person
const d=people[5]; d.userData.reach(1,[0.0,1.44,0.62],[1,-1,0]); 
people[3].userData.reach(-1,[-0.5,1.9,0.5]); people[3].userData.reach(1,[0.5,1.9,0.5]);
people[1].userData.walk(1.2,1);
const b=makeBean('#e74c8c'); b.position.set(-3,0,-6); scene.add(b);
const b2=makeBean('#3fa7d6'); b2.position.set(-1.5,0,-6.5); b2.userData.cheer(0.1); scene.add(b2);
const p1=makePoop(true); p1.position.set(1.4,0,1.5); p1.scale.setScalar(1.2); scene.add(p1);
const p2=makePoop(false); p2.position.set(-1.4,0,1.7); scene.add(p2);
const f=makeFish('#ff9a3c'); f.position.set(2.7,0,-6); f.userData.face.set('sick'); scene.add(f);
const f2=makeFish('#4fb3ff'); f2.position.set(1.2,0,-6.5); f2.userData.face.set('joy'); scene.add(f2);
const t=makeToilet(); t.position.set(3.2,0,-1); scene.add(t);
const cam=new THREE.PerspectiveCamera(35,W/H,0.1,200); cam.position.set(0,6,19); cam.lookAt(0,1.6,-2.5);
const out=document.createElement('canvas'); out.width=W; out.height=H; const ctx=out.getContext('2d');
window.renderFrame=(f,type)=>{renderer.render(scene,cam); ctx.drawImage(renderer.domElement,0,0); return out.toDataURL(type,0.92);};
