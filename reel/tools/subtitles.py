#!/usr/bin/env python3
"""Word-by-word subtitles (ASS, burned in by ffmpeg/libass).

One word at a time, timed from build/placement.json (absolute word times from
the voice files: ElevenLabs alignment when available, otherwise the local TTS
model's own timings). Text comes straight from script.json, so every word is
spelled exactly like the script.

Look: big bold rounded white font (Fredoka Bold), thick black outline, soft
shadow, each word pops in with a tiny bounce. John's line is yellow and a
little bigger. Placed centre, a little above the middle of the frame, away
from the bottom 20% and the right edge (Instagram's buttons).

Usage:  python3 tools/subtitles.py   ->  build/subs.ass
"""
import json
import os

from PIL import ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_FILE = os.path.join(ROOT, "assets", "fonts", "Fredoka_700Bold.ttf")
W, H = 1080, 1920
X, Y = 520, 780            # word centre (a little above the middle, nudged left of the buttons)
MAX_W = 860                # long words shrink to fit
STYLE = {
    "narrator": {"size": 150, "colour": "&HFFFFFF&"},
    "john": {"size": 168, "colour": "&H4AD8FF&"},    # yellow (#FFD84A, written BGR), a little bigger
}
BORDER = 10
LEAD = 0.02                # show each word a hair before it is heard
HOLD = 0.35                # how long a word stays after it ends when a pause follows
LAST_HOLD = 0.5            # last word of a line
LIBASS_SCALE = 118 / 143   # libass sizes fonts by ascent+descent; Pillow by em


def load(rel):
    with open(os.path.join(ROOT, rel)) as f:
        return json.load(f)


def ts(t):
    t = max(0.0, t)
    cs = int(round(t * 100))
    return f"{cs // 360000}:{cs // 6000 % 60:02d}:{cs // 100 % 60:02d}.{cs % 100:02d}"


def main():
    script = load("script.json")
    place = load("build/placement.json")["lines"]
    font_cache = {}

    def width(word, size):
        if size not in font_cache:
            font_cache[size] = ImageFont.truetype(FONT_FILE, max(1, round(size * LIBASS_SCALE)))
        b = font_cache[size].getbbox(word)
        return (b[2] - b[0]) + 2 * BORDER

    # every word with its absolute timing, in film order
    items = []
    for line in script["lines"]:
        tokens = line["text"].split()
        timed = place[line["id"]]["words"]
        if len(tokens) != len(timed):
            raise SystemExit(f"{line['id']}: script has {len(tokens)} words but timings have {len(timed)}")
        for k, (tok, tw) in enumerate(zip(tokens, timed)):
            items.append({"word": tok, "start": tw["start"], "end": tw["end"], "speaker": line["speaker"],
                          "last": k == len(tokens) - 1})
    items.sort(key=lambda w: w["start"])

    events = []
    for n, w in enumerate(items):
        start = w["start"] - LEAD
        nxt = items[n + 1]["start"] - LEAD if n + 1 < len(items) else float("inf")
        if nxt - (w["end"] - LEAD) < 0.6:
            end = nxt                                   # hand straight over to the next word
        else:
            end = min(w["end"] + (LAST_HOLD if w["last"] else HOLD), nxt)
        end = max(end, min(start + 0.12, nxt))          # never a flash-frame word, never two at once
        st = STYLE[w["speaker"]]
        fit = min(1.0, MAX_W / width(w["word"], st["size"]))
        sc = lambda p: round(p * fit)  # noqa: E731
        # pop-in with a tiny bounce; quick enough that even a 3-frame word is readable
        pop = (f"\\fscx{sc(70)}\\fscy{sc(70)}\\t(0,70,\\fscx{sc(110)}\\fscy{sc(110)})"
               f"\\t(70,130,\\fscx{sc(97)}\\fscy{sc(97)})\\t(130,180,\\fscx{sc(100)}\\fscy{sc(100)})")
        text = w["word"].replace("{", "(").replace("}", ")")
        shadow = (f"{{\\an5\\pos({X},{Y + 9})\\fs{st['size']}{pop}\\1c&H000000&\\3c&H000000&"
                  f"\\1a&H78&\\3a&H78&\\bord{BORDER + 2}\\shad0\\blur10}}{text}")
        main_t = (f"{{\\an5\\pos({X},{Y})\\fs{st['size']}{pop}\\1c{st['colour']}\\3c&H000000&"
                  f"\\bord{BORDER}\\shad0\\blur0.7}}{text}")
        events.append(f"Dialogue: 0,{ts(start)},{ts(end)},Word,,0,0,0,,{shadow}")
        events.append(f"Dialogue: 1,{ts(start)},{ts(end)},Word,,0,0,0,,{main_t}")

    head = f"""[Script Info]
; one word at a time, generated by tools/subtitles.py from script.json + build/placement.json
ScriptType: v4.00+
PlayResX: {W}
PlayResY: {H}
WrapStyle: 2
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Word,Fredoka,150,&H00FFFFFF,&H00FFFFFF,&H00000000,&H00000000,-1,0,0,0,100,100,0,0,1,{BORDER},0,5,0,0,0,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    out = os.path.join(ROOT, "build", "subs.ass")
    with open(out, "w", encoding="utf-8") as f:
        f.write(head + "\n".join(events) + "\n")
    print(f"wrote build/subs.ass ({len(items)} words)")


if __name__ == "__main__":
    main()
