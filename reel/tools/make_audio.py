SFX = {k[4:]: v for k, v in globals().items() if k.startswith('sfx_')}


# ============================================================================ music
BPM = 112
BEAT = 60 / BPM
NOTE = {n: i for i, n in enumerate(['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'])}


def midi(name):
    return 12 * (int(name[-1]) + 1) + NOTE[name[:-1]]


def hz(m):
    return 440 * 2 ** ((m - 69) / 12)


CHORDS = {'D': ['D', 'F#', 'A'], 'A': ['A', 'C#', 'E'], 'Bm': ['B', 'D', 'F#'], 'G': ['G', 'B', 'D'], 'Em': ['E', 'G', 'B'], 'F#m': ['F#', 'A', 'C#'], 'Gm': ['G', 'A#', 'D']}


def pluck(f, d, bright=0.6, seed=0):
    """Karplus-Strong plucked string (pizzicato / marimba-ish), as an IIR comb filter."""
    n = int(d * SR); p = max(2, int(SR / f))
    burst = np.random.default_rng(seed).uniform(-1, 1, p)
    burst = filt(burst, 'low', 1200 + 6000 * bright) if p > 32 else burst
    x = np.zeros(n); x[:p] = burst
    a = np.zeros(p + 2); a[0] = 1; a[p] = -0.498; a[p + 1] = -0.498
    out = signal.lfilter([1.0], a, x)
    return out * (1 - np.exp(-np.arange(n) / SR / 0.002))


_pluck_cache = {}


def pluck_c(m, d, bright=0.6):
    key = (m, round(d, 2), bright)
    if key not in _pluck_cache:
        _pluck_cache[key] = pluck(hz(m), d, bright, m)
    return _pluck_cache[key]


def pad(freqs, d, bright=1200):
    n = int(d * SR)
    x = np.zeros(n)
    for f in freqs:
        for det in (-0.12, 0.0, 0.11):
            x += osc(f * 2 ** (det / 12), n, 'saw', RNG.uniform(0, 6))
    x = filt(x, 'low', bright) * adsr(n, 0.35, 0.3, 0.8, 0.5)
    return x / len(freqs)


def taiko(d=0.9, f0=110, seed=0):
    n = int(d * SR); t = tvec(d)
    body = np.sin(2 * np.pi * (f0 * 0.45 + f0 * np.exp(-t / 0.04)) * t) * env_exp(n, 0.22)
    slap = filt(noise(n, seed), 'band', (200, 2000)) * env_exp(n, 0.012) * 0.5
    return body + slap


def hat(seed=0):
    n = int(0.08 * SR)
    return filt(noise(n, seed), 'high', 7000) * env_exp(n, 0.015)


def brass(freqs, d):
    n = int(d * SR); t = tvec(d)
    x = sum(osc(f, n, 'saw') for f in freqs) / len(freqs)
    cut = 600 + 2600 * np.exp(-t / 0.25) * (1 - np.exp(-t / 0.02))
    # time-varying lowpass approximated in blocks
    out = np.zeros(n); blk = 1024
    for i in range(0, n, blk):
        out[i:i + blk] = filt(x[max(0, i - 2048):i + blk], 'low', float(cut[i]))[-min(blk, n - i):]
    return out * adsr(n, 0.04, 0.15, 0.7, 0.25)


def glock(m, d=1.2):
    return bell(hz(m), d, m, 0.8) * 0.6


def music(duration, scenes, cut_at, events):
    L = np.zeros((int(duration * SR) + SR, 2))
    sec = lambda b: b * BEAT
    prog = ['D', 'A', 'Bm', 'G']
    total_beats = int(cut_at / BEAT) + 1
    # intensity per time from the scenes
    def inten(t):
        if t < 7.6: return 0.45
        if t < 8.6: return 0.25           # comic dip on the clang
        if t < 20.6: return 0.65
        if t < 23.6: return 0.6
        if t < 25.0: return 0.3           # train slides back: everything wilts
        if t < 28.8: return 0.7
        if t < 35.8: return 0.85
        if t < 42.2: return 1.0
        return 0.5
    melody_pent = ['D5', 'E5', 'F#5', 'A5', 'B5', 'D6']
    mel_pattern = [0, 2, 3, 2, 4, 3, 2, 1, 0, 2, 3, 5, 4, 3, 2, 3]
    for b in range(total_beats):
        t = sec(b)
        if t >= cut_at:
            break
        bar, beat = divmod(b, 4)
        ch = prog[bar % 4]
        if 23.6 <= t < 25.0:
            ch = 'Gm'
        I = inten(t)
        tones = [midi(n + '3') for n in CHORDS[ch]]
        root = midi(CHORDS[ch][0] + '2')
        # pad on each bar
        if beat == 0:
            p = pad([hz(m + 12) for m in tones], sec(4) + 0.4, 900 + 1800 * I) * (0.16 + 0.12 * I)
            place(L, stereo(p, 0.0, 0.8), t)
            # bass
            bn = int(sec(4) * SR)
            bass = (np.sin(2 * np.pi * hz(root) * tvec(sec(4))) + 0.3 * np.tanh(3 * np.sin(2 * np.pi * hz(root) * tvec(sec(4))))) * adsr(bn, 0.01, 0.4, 0.6, 0.2)
            if t >= 7.6:
                place(L, stereo(bass * 0.32 * I, 0.0), t)
        # plucky ostinato on 8ths
        for half in (0, 1):
            tt = t + half * BEAT / 2
            if tt >= cut_at: break
            m = tones[(b * 2 + half) % 3] + 12 * ((b // 2) % 2)
            if 23.6 <= tt < 25.0:
                m -= (b * 2 + half) % 4  # droopy
            pl = pluck_c(m, 0.5, 0.4 + 0.4 * I) * (0.22 + 0.12 * I)
            place(L, stereo(pl, -0.35 + 0.7 * ((b * 2 + half) % 2), 0.2), tt)
        # melody (playful) from scene 2 on, sparser in calm parts
        if t >= 7.6 and not (23.6 <= t < 25.0) and (b % 2 == 0 or I > 0.8):
            mm = midi(melody_pent[mel_pattern[b % 16]])
            mel = pluck_c(mm, 0.7, 0.85) * (0.18 + 0.14 * I)
            place(L, stereo(mel, 0.25, 0.4), t)
        # drums
        if t >= 3.8:
            if beat in (0, 2) or (I > 0.8 and beat == 3):
                place(L, stereo(taiko(0.9, 100 if beat == 0 else 130, b) * (0.35 + 0.35 * I), 0.0, 0.3), t)
            if I > 0.55:
                for q in range(2):
                    place(L, stereo(hat(b * 2 + q) * 0.12 * I, 0.4, 0.1), t + q * BEAT / 2)
        # epic brass stabs in the big scenes
        if t >= 28.8 and t < 42.2 and beat == 0:
            place(L, stereo(brass([hz(m + 12) for m in tones], sec(1.5)) * 0.11 * I, 0.0, 0.7), t)
        # glockenspiel sparkle on scene starts
    for s in scenes:
        if s['start'] < cut_at:
            for k, n in enumerate(['A5', 'D6', 'F#6']):
                place(L, stereo(glock(midi(n)) * 0.25, 0.3, 0.5), s['start'] + k * 0.09)
    # a sad slide-whistle-ish droop when the train slides back
    d = 1.0; n = int(d * SR); tt = tvec(d)
    droop = np.sin(2 * np.pi * np.cumsum(880 * 2 ** (-tt * 1.2)) / SR) * adsr(n, 0.02, 0.2, 0.7, 0.2) * 0.12
    place(L, stereo(droop, 0.0, 0.3), 23.75)
    L = add_reverb(L, IR_HALL, 0.28)
    # HARD stop: nothing at all after the cut (comic timing)
    L[int(cut_at * SR):] = 0
    return L[:int(duration * SR)]


# ============================================================================ mix
def envelope_follow(x, attack=0.02, release=0.6):
    a = np.abs(x).max(1) if x.ndim == 2 else np.abs(x)
    blk = 240
    rms = np.sqrt(np.add.reduceat(a ** 2, np.arange(0, len(a), blk)) / blk)
    env = np.zeros_like(rms); ca = np.exp(-blk / SR / attack); cr = np.exp(-blk / SR / release)
    for i in range(1, len(rms)):
        c = ca if rms[i] > env[i - 1] else cr
        env[i] = c * env[i - 1] + (1 - c) * rms[i]
    return np.repeat(env, blk)[:len(a)]


def main():
    tl = json.load(open(os.path.join(ROOT, 'timeline.json')))
    placed = json.load(open(os.path.join(OUT, 'voice_placement.json')))
    dur = tl['duration']
    N = int(dur * SR)
    voice = np.zeros((N, 2))
    for lid, p in placed.items():
        a, sr = sf.read(os.path.join(ROOT, p['file']))
        assert sr == SR, f'{lid}: expected {SR} Hz'
        if a.ndim == 2:
            a = a.mean(1)
        a = norm(a, 0.95)
        v = stereo(a, 0.0)
        if p['speaker'] == 'john':
            v = add_reverb(np.vstack([v, np.zeros((SR, 2))]), IR_HALL, 0.18)  # a touch of station echo
        place(voice, v, p['start'])
    john_start = placed['07_john']['start']
    cut_at = john_start - tl['music']['cut_before_john']

    sfx_bus = np.zeros((N, 2))
    for e in tl['sfx']:
        fn = SFX[e['type']]
        x = fn(e.get('dur', 1.0), {'t': e['t'], 'underground': tl['underground']})
        place(sfx_bus, x * e.get('gain', 1.0), e['t'])
    # quiet station room tone after the music stops, so the silence feels like a place
    n_tail = N - int(cut_at * SR)
    room = filt(brown(n_tail, 991), 'low', 220) * 0.02 + np.sin(2 * np.pi * 100 * tvec(n_tail / SR)) * 0.002
    place(sfx_bus, stereo(room, 0.0, 0.8), cut_at)

    mus = music(dur, tl['scenes'], cut_at, tl['sfx'])

    # duck music (about -9 dB) and effects (about -4 dB) while someone speaks
    env = envelope_follow(voice)
    env = env / (env.max() + 1e-9)
    duck_m = 1 - 0.78 * np.clip(env * 5, 0, 1)
    duck_s = 1 - 0.37 * np.clip(env * 4, 0, 1)
    stems = {'voice': voice * 1.0, 'music': mus * 0.55 * duck_m[:, None], 'sfx': sfx_bus * 0.42 * duck_s[:, None]}
    os.makedirs(os.path.join(OUT, 'stems'), exist_ok=True)
    for k, v in stems.items():
        sf.write(os.path.join(OUT, 'stems', f'{k}.wav'), v.astype(np.float32), SR, subtype='FLOAT')
    mix = stems['voice'] + stems['music'] + stems['sfx']
    mix = np.tanh(mix * 0.9) / 0.9  # gentle safety saturation on stray peaks
    tmp = os.path.join(OUT, 'mix_raw.wav')
    sf.write(tmp, mix.astype(np.float32), SR, subtype='FLOAT')
    sf.write(os.path.join(OUT, 'music_only.wav'), mus.astype(np.float32), SR, subtype='FLOAT')
    # loudness: two-pass EBU R128 to -14 LUFS, -1 dBTP, linear (keeps the hard music cut intact)
    r = subprocess.run(['ffmpeg', '-hide_banner', '-i', tmp, '-af', 'loudnorm=I=-14:TP=-1.0:LRA=11:print_format=json', '-f', 'null', '-'], capture_output=True, text=True)
    js = json.loads(r.stderr[r.stderr.rindex('{'):r.stderr.rindex('}') + 1])
    af = (f"loudnorm=I=-14:TP=-1.0:LRA=11:linear=true:measured_I={js['input_i']}:measured_TP={js['input_tp']}:"
          f"measured_LRA={js['input_lra']}:measured_thresh={js['input_thresh']}:offset={js['target_offset']}")
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', tmp, '-af', af, '-ar', str(SR), '-c:a', 'pcm_s24le', os.path.join(OUT, 'mix.wav')], check=True)
    os.remove(tmp)
    print(f'[audio] mix.wav written; music cut at {cut_at:.2f}s (John speaks at {john_start:.2f}s); input loudness {js["input_i"]} LUFS')


if __name__ == '__main__':
    main()
