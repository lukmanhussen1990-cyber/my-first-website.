def grains(dur, density, seed, lo=200, hi=3000, size=0.01):
    n = int(dur * SR); out = np.zeros(n); r = np.random.default_rng(seed)
    for _ in range(int(density * dur)):
        k = int(r.uniform(0, dur) * SR); m = int(r.uniform(0.5, 1.5) * size * SR)
        g = noise(m, int(r.integers(1e6))) * env_exp(m, size * 0.4) * r.uniform(0.3, 1)
        out[k:k + m] += g[:max(0, min(m, n - k))]
    return filt(out, 'band', (lo, hi))


