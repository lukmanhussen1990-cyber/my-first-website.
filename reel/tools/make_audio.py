def bell(f, d, seed=0, bright=1.0):
    n = int(d * SR); t = tvec(d)
    x = np.zeros(n)
    for ratio, a, tau in ((1, 1, 1.2), (2.0, 0.45, 0.7), (2.76, 0.35 * bright, 0.45), (5.4, 0.2 * bright, 0.2), (8.93, 0.1 * bright, 0.1)):
        x += a * np.sin(2 * np.pi * f * ratio * t) * env_exp(n, tau * d / 1.6)
    return x * (1 - np.exp(-t / 0.002))


