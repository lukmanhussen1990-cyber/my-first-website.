"""Synthesised music + sound effects, mixed under the voices -> out/mix.wav (48 kHz stereo)

    python3 tools/make_audio.py

Everything is generated by code (no samples). Sound effects come from timeline.json "sfx";
voices come from out/voice_placement.json (run tools/place_voices.py first). The music follows
the scenes and stops dead right before John's line. Music and effects duck under the voice.
"""
