import numpy as np
import soundfile as sf
from scipy import signal

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
OUT = os.path.join(ROOT, 'out')
SR = 48000
RNG = np.random.default_rng(2026)


# ============================================================================ DSP helpers
def tvec(dur):
    return np.arange(int(dur * SR)) / SR


def noise(n, seed=None):
    r = np.random.default_rng(seed) if seed is not None else RNG
    return r.standard_normal(n)


def brown(n, seed=None):
    x = np.cumsum(noise(n, seed)); x = signal.lfilter([1, -1], [1, -0.995], x)
    return x / (np.abs(x).max() + 1e-9)


def filt(x, kind, f, order=2):
    nyq = SR / 2
    if kind == 'band':
        sos = signal.butter(order, [max(10, f[0]) / nyq, min(f[1], nyq * 0.98) / nyq], 'bandpass', output='sos')
    else:
        sos = signal.butter(order, min(f, nyq * 0.98) / nyq, kind, output='sos')
    return signal.sosfilt(sos, x)


def env_exp(n, tau):
    return np.exp(-np.arange(n) / SR / tau)


def adsr(n, a=0.01, d=0.1, s=0.7, r=0.2):
    t = np.arange(n) / SR; dur = n / SR
    e = np.where(t < a, t / max(a, 1e-4), np.where(t < a + d, 1 - (1 - s) * (t - a) / max(d, 1e-4), s))
    rel = np.clip((dur - t) / max(r, 1e-4), 0, 1)
    return e * rel


def osc(freq, n, kind='sine', phase=0.0):
    f = np.broadcast_to(np.asarray(freq, dtype=float), (n,)) if np.ndim(freq) else np.full(n, float(freq))
    ph = 2 * np.pi * np.cumsum(f) / SR + phase
    if kind == 'sine':
        return np.sin(ph)
    if kind == 'saw':  # band-limited-ish: sum of harmonics under nyquist
        out = np.zeros(n); fmax = f.max()
        for k in range(1, int(min(40, (SR / 2) / max(fmax, 1)))):
            out += np.sin(k * ph) / k
        return out * 0.6
    if kind == 'square':
        out = np.zeros(n); fmax = f.max()
        for k in range(1, int(min(40, (SR / 2) / max(fmax, 1))), 2):
            out += np.sin(k * ph) / k
        return out * 0.8
    if kind == 'tri':
        return signal.sawtooth(ph, 0.5)
    raise ValueError(kind)


def stereo(x, pan=0.0, width=0.0, seed=1):
    """pan -1..1; width adds a decorrelated copy for space."""
    l = x * np.sqrt(0.5 * (1 - pan)); r = x * np.sqrt(0.5 * (1 + pan))
    if width > 0:
        d = int(0.011 * SR)
        y = np.concatenate([np.zeros(d), x[:-d]]) if len(x) > d else x
        l = l * (1 - width * 0.3) + y * width * 0.3; r = r * (1 - width * 0.3) - y * width * 0.15 + x * width * 0.15
    return np.stack([l, r], 1)


def reverb_ir(dur=2.2, decay=0.6, seed=7, bright=6000):
    n = int(dur * SR)
    ir = np.stack([noise(n, seed), noise(n, seed + 1)], 1) * env_exp(n, decay)[:, None]
    ir = np.stack([filt(ir[:, 0], 'low', bright), filt(ir[:, 1], 'low', bright)], 1)
    ir[:int(0.004 * SR)] = 0
    return ir / np.sqrt((ir ** 2).sum(0, keepdims=True))


IR_HALL = reverb_ir(2.4, 0.55, 7, 7000)
IR_ROOM = reverb_ir(0.9, 0.18, 9, 9000)


def add_reverb(x, ir, wet=0.25):
    y = np.stack([signal.fftconvolve(x[:, c], ir[:, c])[:len(x)] for c in range(2)], 1)
    return x * (1 - wet * 0.5) + y * wet


def place(bus, x, t):
    i = int(round(t * SR))
    if i >= len(bus):
        return
    if i < 0:
        x = x[-i:]; i = 0
    m = min(len(x), len(bus) - i)
    bus[i:i + m] += x[:m]


def norm(x, peak=0.9):
    return x / (np.abs(x).max() + 1e-9) * peak


def fade(x, a=0.01, b=0.05):
    n = len(x); fa = min(n, int(a * SR)); fb = min(n, int(b * SR))
    w = np.ones(n); w[:fa] = np.linspace(0, 1, fa); w[n - fb:] = np.minimum(w[n - fb:], np.linspace(1, 0, fb))
    return x * (w[:, None] if x.ndim == 2 else w)


# ============================================================================ sound effects
def sfx_wind(dur, ctx):
    n = int(dur * SR); t = tvec(dur)
    base = brown(n, 11) * 0.6 + filt(noise(n, 12), 'low', 900) * 0.4
    gust = 0.55 + 0.45 * np.sin(2 * np.pi * 0.11 * t + 1.0) * np.sin(2 * np.pi * 0.047 * t)
    whistle = filt(noise(n, 13), 'band', (700, 1400)) * (0.15 + 0.15 * np.sin(2 * np.pi * 0.07 * t))
    x = filt(base, 'band', (60, 2200)) * gust + whistle * gust
    # under ground: darker and quieter
    ug = np.zeros(n)
    for a, b in ctx['underground']:
        ug += np.clip((t - a) / 0.8, 0, 1) * np.clip((b - t) / 0.8, 0, 1)
    ug = np.clip(ug, 0, 1)
    dark = filt(x, 'low', 300)
    x = x * (1 - ug) + dark * ug * 0.35
    return fade(np.stack([x, np.roll(x, 400) * 0.9 + filt(noise(n, 14), 'low', 500) * 0.05], 1), 1.0, 1.0)


def engine(dur, rpm0=900, rpm1=900, seed=21, grit=0.35):
    n = int(dur * SR); t = tvec(dur)
    rpm = np.linspace(rpm0, rpm1, n) * (1 + 0.02 * np.sin(2 * np.pi * 0.7 * t))
    fire = rpm / 60 * 3  # 6 cylinder, 4 stroke
    ph = 2 * np.pi * np.cumsum(fire) / SR
    pulses = np.maximum(0, np.sin(ph)) ** 6
    tone = np.zeros(n)
    for k, a in ((0.5, 0.6), (1, 1.0), (2, 0.5), (3, 0.25)):
        tone += a * np.sin(k * ph + k)
    rumble = filt(tone * (0.6 + 0.4 * pulses), 'low', 380) + filt(noise(n, seed) * pulses, 'band', (100, 900)) * grit
    return rumble


def sfx_diesel(dur, ctx):
    x = engine(dur, 820, 900, 21)
    return fade(stereo(norm(x, 0.8), -0.1, 0.4), 0.4, 0.6)


def sfx_diesel_truck(dur, ctx):
    x = engine(dur, 900, 1700, 23, 0.5) * np.linspace(1, 0.3, int(dur * SR))
    return fade(stereo(norm(x, 0.8), -0.5, 0.3), 0.05, 0.5)


def clank_train(dur, rate, seed, bright=3200):
    n = int(dur * SR); out = np.zeros(n); r = np.random.default_rng(seed)
    t = 0.0
    while t < dur:
        k = int(t * SR); m = int(0.06 * SR)
        hit = noise(m, int(r.integers(1e6))) * env_exp(m, 0.008)
        ping = np.sin(2 * np.pi * r.uniform(bright * 0.7, bright * 1.2) * np.arange(m) / SR) * env_exp(m, 0.015) * 0.5
        thump = np.sin(2 * np.pi * 90 * np.arange(m) / SR) * env_exp(m, 0.02) * 0.6
        s = filt(hit, 'band', (900, 6000)) * 0.6 + ping + thump
        out[k:k + m] += s[:max(0, min(m, n - k))]
        t += 1 / rate * r.uniform(0.85, 1.15)
    return out


