def sfx_whoosh(dur, ctx):
    n = int(dur * SR); t = tvec(dur); u = t / dur
    x = noise(n, 151)
    # sweep a band through the noise, loud in the middle
    out = np.zeros(n)
    for k, (lo, hi) in enumerate(((150, 600), (500, 1800), (1500, 5000))):
        out += filt(x, 'band', (lo, hi)) * np.exp(-((u - (0.35 + 0.12 * k)) / 0.22) ** 2)
    out += filt(brown(n, 152), 'low', 180) * np.exp(-((u - 0.4) / 0.3) ** 2) * 1.2
    pan = np.clip(-1 + 2 * u, -1, 1)
    l = out * np.sqrt(0.5 * (1 - pan)); r = out * np.sqrt(0.5 * (1 + pan))
    return norm(np.stack([l, r], 1), 0.9)


