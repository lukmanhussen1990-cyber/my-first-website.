#!/usr/bin/env python3
"""Synthesize the music score and all sound effects from the shared timeline.

Reads build/timeline.json (written by tools/dump_timeline.mjs) and writes
  audio/stems/music.flac  (score; crashes to silence at the battery-empty moment)
  audio/stems/sfx.flac    (all sound effects)
Everything is generated by code (no samples).
"""
import json, os, sys
import numpy as np
import soundfile as sf
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from synth import *  # noqa

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TL = json.load(open(os.path.join(ROOT, 'build/timeline.json')))
E = TL['events']
DUR = TL['duration'] + 0.5
C = {k: np.array(v) for k, v in TL['curves'].items()}
CRASH = E['drainEnd']  # music crashes to silence when the battery hits empty
rng = np.random.default_rng(42)


def curve_at(name, t):
    return np.interp(t, C['t'], C[name])


def curve_samples(name, n, t0=0.0):
    t = t0 + np.arange(n) / SR
    return np.interp(t, C['t'], C[name])


# =====================================================================================  MUSIC
def music():
    M = Track(DUR)       # dry
    W = Track(DUR)       # wet send (big hall)
    # ---------------- Section A: playful (0 - 33.4), C major, 112 BPM ----------------
    bpm = 112; beat = 60 / bpm; bar = 4 * beat
    prog = [('C', [60, 64, 67], 36), ('A', [57, 60, 64], 33), ('F', [57, 60, 65], 29), ('G', [55, 59, 62], 31)]
    mel_pat = [  # scale-degree offsets per 8th note, per chord (semitones from chord root, C-major friendly)
        [12, 16, 19, 16, 14, 12, 7, 9],
        [12, 9, 7, 9, 12, 16, 14, 12],
        [9, 12, 17, 16, 14, 12, 9, 7],
        [11, 14, 19, 17, 14, 11, 7, 2],
    ]
    t0 = 0.15
    nbars = int((33.4 - t0) / bar) + 1
    for b in range(nbars):
        tb = t0 + b * bar
        name, chord, root = prog[b % 4]
        scene = 1 + int(tb / 6.6)
        tired = 27.3 < tb < 29.4
        if tb > 33.4:
            break
        # pizzicato bass: root / fifth walking
        for k, (off, step) in enumerate([(0, 0), (2, 7), (0, 12), (2, 7)]) if not tired else enumerate([(0, 0), (2, 7)]):
            tn = tb + k * beat * (1 if not tired else 2)
            f = midi(root + step)
            M.add(tn, karplus(f, 0.9, bright=0.35, decay=0.993), 0.55, -0.1)
        # off-beat ukulele/pizz chord stabs
        if not tired:
            for k in range(4):
                tn = tb + k * beat + beat / 2
                for j, m in enumerate(chord):
                    M.add(tn + j * 0.006, karplus(midi(m), 0.5, bright=0.7, decay=0.985), 0.16, 0.25 - j * 0.1)
        # marimba melody from scene 2
        if scene >= 2 and not tired:
            pat = mel_pat[b % 4]
            for k, off in enumerate(pat):
                if scene < 4 and k % 2 == 1:
                    continue
                tn = tb + k * beat / 2
                if tn > 33.3:
                    break
                M.add(tn, marimba(midi(root + 24 + off - 12), 0.6), 0.22 * (0.9 if k % 2 else 1.0), 0.15)
                W.add(tn, marimba(midi(root + 24 + off - 12), 0.6), 0.05)
        # percussion builds per scene
        for k in range(8):
            tn = tb + k * beat / 2
            if tn > 33.4:
                break
            if scene >= 2 and not tired:
                M.add(tn, shaker(0.9 if k % 2 else 0.6), 0.5, 0.3)
            if scene >= 3 and k in (2, 6) and not tired:
                M.add(tn, clap(), 0.35, -0.05)
            if scene >= 3 and k in (0, 4):
                M.add(tn, kick(0.4, 120, 48), 0.35)
        if scene >= 4 and not tired:
            M.add(tb + 3.5 * beat, hat(0.8, True), 0.25, 0.4)
    # tired: a deflating trombone-ish slide
    n = int(1.4 * SR); tt = np.arange(n) / SR
    f = 196 * 2 ** (-np.minimum(tt, 1.2) / 1.2 * 0.6)
    tb_ = lp(saw(f, n), 1300) * env_adsr(n, 0.05, 0.2, 0.8, 0.4)
    M.add(27.6, tb_, 0.22, -0.2)
    # glockenspiel 'idea!' accents on each smart fix
    for te in [E['genBase'], E['bigGear'], E['batteryPop'], E['rodPop']]:
        for j, m in enumerate([84, 88, 91, 96]):
            M.add(te - 0.12 + j * 0.06, glock(midi(m), 1.2), 0.18, 0.2)
            W.add(te - 0.12 + j * 0.06, glock(midi(m), 1.2), 0.08)
    # ---------------- Transition: storm arrives (33.4 - 35.3) ----------------
    n = int(2.6 * SR); tt = np.arange(n) / SR
    drone = pad([midi(36), midi(43), midi(48)], 2.6, a=1.2, r=0.8, cutoff=500, voices=3)
    M.add(33.3, drone, 0.5)
    rs = bp(noise(n), 300, 6000) * (tt / 2.6) ** 2.5
    M.add(33.0, hp(rs, 400), 0.12, 0.0); W.add(33.0, rs, 0.08)
    # timpani roll
    for k in range(26):
        tk = 33.6 + k * 0.065
        M.add(tk, taiko(0.6, 90, 55, vel=0.15 + 0.6 * k / 26), 0.35, rng.uniform(-0.3, 0.3))
    # ---------------- Section B: epic storm (35.3 - 53.0), C minor, 100 BPM ----------------
    bpm2 = 100; bt = 60 / bpm2; br = 4 * bt
    Bt0 = 35.3
    progB = [([48, 51, 55], 36), ([44, 48, 51], 32), ([51, 55, 58], 39), ([46, 50, 53], 34)]  # Cm Ab Eb Bb
    nbB = int((53.0 - Bt0) / br) + 1
    ost = [0, 0, 3, 0, 7, 0, 10, 0, 0, 0, 3, 0, 8, 7, 3, 2]
    for b in range(nbB):
        tb = Bt0 + b * br
        chord, root = progB[b % 4]
        if tb >= 53.0:
            break
        phase = 'storm' if tb < 40.4 else 'tense' if tb < 43.1 else 'build' if tb < 44.2 else 'drive'
        # low strings / brass pad
        cut = 900 if phase in ('storm', 'tense') else 1600
        p_ = pad([midi(root), midi(root + 7), midi(root + 12)], br + 0.4, a=0.25, r=0.5, cutoff=cut, voices=3)
        M.add(tb, p_, 0.28 if phase != 'tense' else 0.18)
        W.add(tb, p_, 0.12)
        hi = pad([midi(m + 12) for m in chord], br + 0.4, a=0.4, r=0.6, cutoff=3000, voices=3, vib=0.004)
        M.add(tb, hi, 0.12 if phase != 'tense' else 0.06, 0.2); W.add(tb, hi, 0.1)
        # drums
        if phase == 'storm':
            for k in (0, 2.5):
                M.add(tb + k * bt, taiko(1.6, 110, 46, 1.0), 0.55, 0.0); W.add(tb + k * bt, taiko(1.6, 110, 46), 0.25)
        elif phase == 'tense':
            for k in (0, 0.45, 2, 2.45):  # heartbeat
                M.add(tb + k * bt, taiko(0.9, 80, 40, 0.8 if k in (0, 2) else 0.5), 0.5)
            # high tremolo strings
            ntr = int(br * SR); ttr = np.arange(ntr) / SR
            trem = pad([midi(72), midi(75)], br, a=0.3, r=0.3, cutoff=4000, voices=2) * (0.6 + 0.4 * np.sin(2 * np.pi * 14 * ttr))
            M.add(tb, trem, 0.06, 0.3); W.add(tb, trem, 0.06)
        else:
            # 16th ostinato strings
            for k in range(16):
                tn = tb + k * bt / 4
                if tn >= 53.0:
                    break
                f = midi(root + 24 + ost[k])
                nn = int(0.16 * SR)
                st = lp(saw(f, nn), 2600) * env_adsr(nn, 0.005, 0.05, 0.5, 0.08)
                M.add(tn, st, 0.09 * (1.3 if k % 4 == 0 else 1.0), 0.35 if k % 2 else -0.35)
            if phase == 'build':
                for k in range(16):  # snare roll crescendo
                    M.add(tb + k * bt / 4, snare(0.2, 0.3 + 0.7 * k / 16), 0.18, 0.1)
            else:
                for k in (0, 1, 1.5, 2, 3, 3.5):
                    M.add(tb + k * bt, taiko(1.2, 120, 50, 1.0 if k in (0, 2) else 0.65), 0.45, -0.1 if k % 1 else 0.1)
                    W.add(tb + k * bt, taiko(1.2, 120, 50), 0.15)
                M.add(tb + 1 * bt, snare(0.3, 0.8), 0.22); M.add(tb + 3 * bt, snare(0.3, 0.9), 0.22)
                for k in range(8):
                    M.add(tb + k * bt / 2, hat(0.6), 0.25, 0.4)
                # brass stabs
                if b % 2 == 0:
                    nb_ = int(0.5 * SR)
                    brs = lp(sum(saw(midi(m), nb_) for m in [root + 12, root + 19, root + 24]), 2200) * env_adsr(nb_, 0.02, 0.15, 0.4, 0.2)
                    M.add(tb, brs, 0.2); W.add(tb, brs, 0.12)
    # BRAAM on lightning strike + crash cymbal
    def braam(t, root=36, dur=3.5, g=0.9):
        n_ = int(dur * SR); tt_ = np.arange(n_) / SR
        x = sum(saw(midi(m) * (1 + 0.003 * np.sin(2 * np.pi * 0.7 * tt_ + m)), n_) for m in [root, root + 7, root + 12, root + 15])
        fc = 300 + 2200 * np.exp(-tt_ * 1.2) * np.minimum(1, tt_ * 12)
        x = onepole_lp_curve(x, fc)
        x = np.tanh(x * 1.8) * env_adsr(n_, 0.03, 0.4, 0.75, 1.6)
        M.add(t, x, 0.35 * g); W.add(t, x, 0.22 * g)
        sub = sine(50 * np.exp(-tt_ * 0.4) + 25, n_) * np.exp(-tt_ * 1.5)
        M.add(t, sub, 0.5 * g)
    braam(E['lightning'] + 0.02, 36)
    M.add(E['lightning'], cymbal(4.0, 1.0), 0.6); W.add(E['lightning'], cymbal(4.0), 0.3)
    # blackout: descending strings
    n = int(2.4 * SR); tt = np.arange(n) / SR
    for m in [72, 67, 63]:
        f = midi(m) * 2 ** (-tt / 2.4 * 1.0)
        x = lp(saw(f, n), 2500) * env_adsr(n, 0.2, 0.3, 0.8, 0.6)
        M.add(36.5, x, 0.08, 0.2); W.add(36.5, x, 0.08)
    # neighbors: sad high pad
    sp = pad([midi(75), midi(79), midi(84)], 2.4, a=0.8, r=1.0, cutoff=3500, voices=3, vib=0.004)
    M.add(38.3, sp, 0.07); W.add(38.3, sp, 0.1)
    braam(E['digNeighbors'] - 0.05, 41, 2.5, 0.55)
    M.add(E['splitDots'] - 1.5, cymbal(1.5, 1.0, reverse=True), 0.5)
    braam(E['sparks'], 36, 2.5, 0.5)
    M.add(E['coolPipes'] - 1.2, cymbal(1.2, 1.0, reverse=True), 0.4)
    M.add(E['coolPipes'], cymbal(3.0, 0.8), 0.35)
    # riser into slow motion
    n = int(1.6 * SR); tt = np.arange(n) / SR
    ris = bp(noise(n), 400, 8000) * (tt / 1.6) ** 3
    M.add(51.4, ris, 0.18); W.add(51.4, ris, 0.12)
    # ---------------- Section C: slow-motion (53.0 - 56.2) ----------------
    braam(53.0, 36, 4.0, 0.9)
    for m, a_ in [(48, 'a'), (55, 'o'), (60, 'a'), (63, 'a'), (67, 'o')]:
        v = formant_voice(midi(m), 3.4, a_) * env_adsr(int(3.4 * SR), 0.6, 0.3, 0.85, 0.8)
        M.add(53.0, v, 0.05); W.add(53.0, v, 0.09)
    for m, a_ in [(44, 'a'), (51, 'o'), (56, 'a'), (60, 'a'), (63, 'o')]:
        v = formant_voice(midi(m), 1.6, a_) * env_adsr(int(1.6 * SR), 0.3, 0.3, 0.85, 0.6)
        M.add(54.9, v, 0.05); W.add(54.9, v, 0.09)
    for tk in [53.0, 54.1, 55.2, 55.75]:
        M.add(tk, taiko(2.2, 70, 34, 1.0), 0.6); W.add(tk, taiko(2.2, 70, 34), 0.35)
    M.add(55.0, cymbal(1.2, 1.0, reverse=True), 0.5)
    # ---------------- Section D: triumph (56.2 - 59.6) ----------------
    Dt0 = 56.2
    progD = [([56, 60, 63], 44), ([58, 62, 65], 46), ([60, 64, 67], 48), ([60, 64, 67], 48)]  # Ab Bb C C
    for b, (chord, root) in enumerate(progD):
        tb = Dt0 + b * bt * 2
        dur = bt * 2 + 0.4 if b < 3 else 1.4
        if tb > 59.6:
            break
        p_ = pad([midi(root), midi(root + 7), midi(root + 12)] + [midi(m) for m in chord], dur, a=0.08, r=0.5, cutoff=2600, voices=3)
        M.add(tb, p_, 0.22); W.add(tb, p_, 0.15)
        for m, a_ in zip(chord, 'aoa'):
            v = formant_voice(midi(m), dur, a_) * env_adsr(int(dur * SR), 0.1, 0.2, 0.9, 0.4)
            M.add(tb, v, 0.04); W.add(tb, v, 0.07)
        for k in range(4):
            M.add(tb + k * bt / 2, taiko(1.0, 130, 52, 1.0 if k == 0 else 0.7), 0.45)
        M.add(tb, cymbal(2.0, 0.8), 0.3)
    # brass fanfare melody
    fan = [(0.0, 72, 0.3), (0.3, 75, 0.3), (0.6, 79, 0.9), (1.5, 77, 0.3), (1.8, 79, 0.3), (2.1, 82, 0.9), (3.0, 84, 0.6)]
    for dt_, m, d in fan:
        nb_ = int((d + 0.2) * SR)
        x = lp(saw(midi(m) * (1 + 0.004 * np.sin(2 * np.pi * 5 * np.arange(nb_) / SR)), nb_) + 0.5 * saw(midi(m - 12), nb_), 2800) * env_adsr(nb_, 0.04, 0.1, 0.85, 0.2)
        M.add(Dt0 + 0.2 + dt_, x, 0.14, -0.15); W.add(Dt0 + 0.2 + dt_, x, 0.1)
    # ---------------- Section E: calm night + playful reprise (59.6 - 64.0) ----------------
    cp = pad([midi(48), midi(55), midi(60), midi(64), midi(67)], 2.6, a=0.4, r=1.0, cutoff=2200, voices=3)
    M.add(59.6, cp, 0.22); W.add(59.6, cp, 0.15)
    for j, m in enumerate([72, 76, 79, 84, 79, 76, 72, 79]):
        M.add(59.8 + j * 0.22, glock(midi(m), 1.0), 0.12, 0.2); W.add(59.8 + j * 0.22, glock(midi(m), 1.0), 0.08)
    for b in range(2):
        tb = 61.6 + b * bar
        for name, chord, root in [prog[(b * 2) % 4], prog[(b * 2 + 1) % 4]]:
            pass
        name, chord, root = prog[b % 4]
        for k in range(4):
            tn = tb + k * beat
            if tn >= CRASH:
                break
            M.add(tn, karplus(midi(root + (0, 7, 12, 7)[k]), 0.8, 0.35, 0.993), 0.5)
            for j, m in enumerate(chord):
                M.add(tn + beat / 2 + j * 0.006, karplus(midi(m), 0.4, 0.7, 0.985), 0.14)
            M.add(tn, marimba(midi(root + 24 + mel_pat[b % 4][k * 2] - 12), 0.5), 0.2)
            M.add(tn, shaker(), 0.4); M.add(tn + beat / 2, shaker(0.7), 0.4)
    # ---------------- mixdown ----------------
    ir = reverb_ir(2.4, 0.03, 5, 7000)
    wet = convolve_stereo(W.buf, ir) * 1.0
    small = convolve_stereo(M.buf, reverb_ir(0.9, 0.015, 9, 8000)) * 0.18
    out = M.buf + wet + small
    # crash to silence at the battery-empty moment: a 0.12 s tape-stop glide, then nothing
    i0 = int(CRASH * SR); L = int(0.12 * SR)
    seg = out[i0:i0 + L * 3].copy()
    rate = np.linspace(1.0, 0.15, L)
    pos = np.cumsum(rate); pos = pos[pos < len(seg) - 1]
    stop = np.stack([np.interp(pos, np.arange(len(seg)), seg[:, c]) for c in range(2)], 1) * np.linspace(1, 0, len(pos))[:, None]
    out[i0:] = 0
    out[i0:i0 + len(stop)] = stop
    # gentle bus compression-ish soft clip
    out = np.tanh(out * 0.9) / 0.9
    return out


# =====================================================================================  SFX
def sfx():
    S = Track(DUR)
    Wt = Track(DUR)  # reverb send
    n_all = S.n
    t_all = np.arange(n_all) / SR
    # ---------- wheel: integrated angle -> creaks & rumble ----------
    run = curve_samples('run', n_all); rate = curve_samples('rate', n_all)
    omega = run * 1.6 * rate
    ang = np.cumsum(omega) / SR
    alive = t_all < CRASH
    rumble = lp(noise(n_all), 160) * np.clip(omega / 2.5, 0, 1.2) * 0.35
    rumble += lp(bp(noise(n_all), 300, 900), 900) * np.clip(omega / 3, 0, 1) * 0.05
    S.buf[:, 0] += rumble * alive; S.buf[:, 1] += rumble * alive
    # creak once per half revolution
    k_prev = 0
    idx = np.nonzero(np.diff(np.floor(ang / np.pi)) > 0)[0]
    for i in idx:
        t = i / SR
        if t >= CRASH or omega[i] < 0.1:
            continue
        n = int(0.32 * SR); tt = np.arange(n) / SR
        f = 900 + 500 * np.sin(np.pi * tt / 0.32) + rng.uniform(-100, 100)
        cr = sine(f, n) * 0.4 + bp(noise(n), 700, 2600) * 0.6
        cr *= np.sin(np.pi * tt / 0.32) ** 2 * (0.6 + 0.4 * (np.sin(2 * np.pi * 37 * tt) > 0))
        g = 0.05 * min(1.0, 0.4 + omega[i] / 3)
        S.add(t, cr, g, -0.3)
    # ---------- footsteps on wooden slats ----------
    for t, spd, r in TL['footsteps']:
        if t >= CRASH:
            continue
        slow = r < 0.6
        n = int(0.35 * SR); tt = np.arange(n) / SR
        thump = sine(110 * (0.7 if slow else 1.0) * np.exp(-tt * 9) + 60, n) * np.exp(-tt * (14 if not slow else 6))
        wood = bp(noise(n), 350, 1600) * np.exp(-tt * (55 if not slow else 18))
        x = thump * 0.8 + wood * 0.7
        g = 0.22 * min(1.2, 0.5 + spd * 0.4)
        S.add(t, x, g, -0.35 + rng.uniform(-0.1, 0.1))
        if slow:
            Wt.add(t, x, g * 0.6)
    # ---------- John's hop / landing / sweatband snap ----------
    S.add(E['johnHop'], bp(noise(int(0.25 * SR)), 200, 3000) * exp_decay(int(0.25 * SR), 0.05), 0.08, -0.4)
    S.add(E['stretch'] - 0.05, kick(0.3, 120, 60, 1.0), 0.25, -0.4)
    n = int(0.12 * SR); S.add(E['sweatband'] + 0.3, hp(noise(n), 1500) * exp_decay(n, 0.01), 0.18, -0.3)
    # ---------- cartoon pops for things snapping into place ----------
    def pop_sfx(t, size=1.0, g=0.35, pan=0.0):
        n = int(0.25 * SR); tt = np.arange(n) / SR
        f = (300 + 900 * (1 - np.exp(-tt * 40))) / size
        x = sine(f, n) * np.exp(-tt * 18) + 0.3 * hp(noise(n), 2000) * np.exp(-tt * 90)
        S.add(t, x, g, pan)
    def clunk(t, g=0.45, pan=0.0, pitch=1.0):
        n = int(0.5 * SR); tt = np.arange(n) / SR
        x = sum(peak(noise(n), f * pitch, q=30, gain=a) for f, a in [(1180, 1.0), (2650, 0.7), (4100, 0.5), (620, 0.6)]) * np.exp(-tt * 14)
        x = x / (np.abs(x).max() + 1e-9) + 0.7 * sine(90, n) * np.exp(-tt * 25)
        S.add(t, x, g, pan); Wt.add(t, x, g * 0.3)
    pop_sfx(E['standPop'], 1.3, 0.3, -0.2); pop_sfx(E['wheelPop'], 1.6, 0.4, -0.2)
    n = int(0.6 * SR); tt = np.arange(n) / SR
    S.add(E['wheelPop'] + 0.05, sine(140 + 60 * np.sin(2 * np.pi * 9 * tt) * np.exp(-tt * 4), n) * np.exp(-tt * 5), 0.25, -0.2)  # boing
    for k, te in enumerate([E['genBase'], E['genHousing'], E['genCoil'], E['genMagnet'], E['genPulley']]):
        pop_sfx(te, 1.0 + k * 0.1, 0.3, 0.2); clunk(te + 0.03, 0.18, 0.2, 1.0 + k * 0.08)
    # belt whip
    n = int(0.45 * SR); tt = np.arange(n) / SR
    wh = bp(noise(n), 400, 4000) * np.sin(np.pi * np.minimum(1, tt / 0.4)) ** 2
    S.add(E['beltWhip'], wh, 0.25, 0.1); clunk(E['beltWhip'] + 0.38, 0.25, 0.1, 1.6)
    # gears clicking into place
    for te in [E['bigGear'], E['gearStand'], E['smallGear']]:
        pop_sfx(te, 1.2, 0.25, 0.25)
    for te, p_ in [(E['bigGear'] + 0.05, 0.9), (E['smallGear'] + 0.05, 1.3), (E['gearClick'], 1.1)]:
        clunk(te, 0.5, 0.25, p_)
    # generator slide (scrape)
    n = int(0.4 * SR); S.add(E['genSlide'], bp(noise(n), 800, 3000) * np.sin(np.pi * np.arange(n) / n), 0.12, 0.3)
    # gear ratchet ticks while gears spin
    gom = curve_samples('genOmega', n_all)
    gang = np.cumsum(gom) / SR
    tick_idx = np.nonzero(np.diff(np.floor(gang * 10 / (2 * np.pi))) > 0)[0]
    last = -1
    for i in tick_idx:
        t = i / SR
        if t < E['gearClick'] or t >= CRASH or t - last < 0.035:
            continue
        last = t
        n = int(0.02 * SR)
        S.add(t, hp(noise(n), 3000) * exp_decay(n, 0.003), 0.03, 0.25)
    # battery pop + lid
    pop_sfx(E['batteryPop'], 1.4, 0.4, 0.3); clunk(E['batteryPop'] + 0.06, 0.4, 0.3, 0.7)
    pop_sfx(E['batteryLid'], 0.9, 0.25, 0.3)
    # fishing rod + snack boing
    pop_sfx(E['rodPole'], 1.1, 0.3, 0.1); pop_sfx(E['rodPop'], 0.8, 0.3, 0.1)
    n = int(0.8 * SR); tt = np.arange(n) / SR
