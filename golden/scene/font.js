// colour icons usable inside text as {smile} / {heart}
const ICONS = {
  smile: { rows: ['..yyy..', '.yyyyy.', 'ykyyyky', 'yyyyyyy', 'ykyyyky', '.ykkky.', '..yyy..'], pal: { y: '#ffd23f', k: '#3a2400' } },
  heart: { rows: ['.pp.pp.', 'ppppppp', 'ppppppp', '.ppppp.', '..ppp..', '...p...', '.......'], pal: { p: '#ff4f8b' } },
};

function tokens(text) {
  const out = [];
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '{') { const j = text.indexOf('}', i); out.push({ icon: text.slice(i + 1, j) }); i = j; }
    else out.push({ ch: text[i] });
  }
  return out;
}
function glyphOf(t) {
  if (t.icon) return { rows: ICONS[t.icon].rows, pal: ICONS[t.icon].pal };
  return { rows: G[t.ch] || G[t.ch.toUpperCase()] || G['?'] };
}

// width in font pixels
export function measure(text) {
  let w = 0;
  for (const t of tokens(text)) w += glyphOf(t).rows[0].length + 1;
  return Math.max(0, w - 1);
}

// Draw text with its top-left at (x, y). s = size of one font pixel in canvas pixels.
export function drawText(ctx, text, x, y, s, { color = '#fff', outline = 0, outlineColor = '#000', shadow = 0 } = {}) {
  const pixels = [];
  let cx = 0;
  for (const t of tokens(text)) {
    const g = glyphOf(t);
    g.rows.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) {
        const c = row[rx];
        if (c === '.' ) continue;
        pixels.push([cx + rx, ry, g.pal ? g.pal[c] : color]);
      }
    });
    cx += g.rows[0].length + 1;
  }
  if (outline > 0) {
    ctx.fillStyle = outlineColor;
    for (const [px, py] of pixels) {
      ctx.fillRect(Math.round(x + px * s - outline), Math.round(y + py * s - outline), Math.ceil(s + outline * 2), Math.ceil(s + outline * 2 + shadow));
    }
  }
  for (const [px, py, c] of pixels) {
    ctx.fillStyle = c;
    ctx.fillRect(Math.round(x + px * s), Math.round(y + py * s), Math.ceil(s), Math.ceil(s));
  }
}

// Centered helper: (cx, cy) is the centre of the cap-height box.
export function drawCentered(ctx, text, cx, cy, s, opts) {
  const w = measure(text) * s;
  drawText(ctx, text, cx - w / 2, cy - 3.5 * s, s, opts);
}
