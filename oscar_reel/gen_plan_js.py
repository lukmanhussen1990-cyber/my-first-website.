"""shots.json -> web/plan.js (the 3D shot plan used by the renderer). Times, places and sync events come from
shots.json (plan.py).  Run: python3 gen_plan_js.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SH = json.load(open(os.path.join(HERE, "shots.json")))


def main():
    out = []
    for s in SH["shots"]:
        out.append({"id": f"s{s['id']:02d}", "loc": s["loc"], "t0": s["t0"], "t1": s["t1"], "say": s["voice"],
                    "size": s["size"], "label": s.get("label"), "desc": s["scene"], "events": s["events"],
                    "captions": s["captions"]})
    js = ["// Shot plan (generated by gen_plan_js.py from shots.json - do not edit by hand).",
          "// Times are seconds in the final video (30 fps). `say` = the voice line during the shot. `events` = sync",
          "// moments (word onsets). `loc` = the place. Hard cuts between all shots.",
          f"export const DURATION = {SH['duration']};   // seconds (= voiceover length, frame-rounded)",
          "export const PLAN = " + json.dumps(out, indent=1) + ";",
          "export function shotAt(t) { for (const s of PLAN) if (t < s.t1) return s; return PLAN[PLAN.length - 1]; }",
          ""]
    open(os.path.join(HERE, "web", "plan.js"), "w").write("\n".join(js))
    print(f"plan.js: {len(out)} shots, {SH['duration']} s")


if __name__ == "__main__":
    main()
